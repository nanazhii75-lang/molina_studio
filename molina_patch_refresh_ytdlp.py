def write_new(path, sha, b64):
    data = base64.b64decode("".join(b64.split()))
    if hashlib.sha256(data).hexdigest() != sha:
        sys.exit("CHECKSUM SALAH untuk " + path + " (skrip rusak saat disalin?)")
    if os.path.exists(path):
        if open(path, "rb").read() == data:
            print("sama      :", path)
            return
        state = "diperbarui:"
    else:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        state = "ditulis   :"
    open(path, "wb").write(data)
    print(state, path)


def edit(path, pairs):
    s = open(path, encoding="utf-8").read()
    changed = False
    for old, new, marker in pairs:
        if marker in s:
            continue
        if old not in s:
            sys.exit("ANCHOR tidak ditemukan di %s:\n%s" % (path, old))
        if s.count(old) != 1:
            sys.exit("ANCHOR ganda di %s:\n%s" % (path, old))
        s = s.replace(old, new)
        changed = True
    if changed:
        open(path, "w", encoding="utf-8").write(s)
        print("diedit    :", path)
    else:
        print("sudah     :", path)


